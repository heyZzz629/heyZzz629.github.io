function expandAliases(answer){
  const list=[answer];
  if(/[\/\s]/.test(answer))return list;
  const map=[["'m",' am'],["'re",' are'],["'s",' is'],["'ve",' have'],["'ll",' will'],["'d",' would'],["n't",' not']];
  for(const kv of map){
    const k=kv[0],v=kv[1];
    if(answer.toLowerCase().includes(k)){
      list.push(answer.replace(new RegExp(k.replace(/[-/\\^$*+?.()|[\]{}]/g,'\\$&'),'gi'),v));
    }
  }
  const back=[['am',"'m"],['are',"'re"],['is',"'s"],['have',"'ve"],['will',"'ll"],['would',"'d"],['not',"n't"]];
  for(const kv of back){
    const k=kv[0],v=kv[1];
    if(new RegExp('\\b'+k+'\\b','i').test(answer)){
      list.push(answer.replace(new RegExp('\\b'+k+'\\b','gi'),v));
    }
  }
  return [...new Set(list)];
}
